/* ============================================================================
   Judgement Cut — ฟันรัวจนจอแตกเป็นชิ้น

   ---------------------------------------------------------------------------
   ทำไมไม่ใช้เสี้ยวแบบแฉกที่แผ่จากจุดเดียว (ของเดิม)

   เพราะมันอ่านผิด ชิ้นที่บรรจบกันหมดที่จุดเดียวตาอ่านเป็น "พาย" หรือ "ดอกไม้ไฟ"
   ไม่ใช่ "ของที่ถูกดาบเฉือน" ของที่ถูกฟันจริงถูกตัดด้วยเส้นตรงที่พาดผ่านทั้งผืน
   หลายเส้น ชิ้นที่ได้จึงเป็นเหลี่ยมไม่สม่ำเสมอและไม่มีจุดร่วม

   ---------------------------------------------------------------------------
   วิธีแบ่ง: ตัดสี่เหลี่ยมจอด้วยเส้นตรงหลายเส้น

   เส้นตรงหนึ่งเส้นแบ่งระนาบเป็นสองฝั่ง เส้น K เส้นจึงแบ่งจอได้สูงสุด
   1 + K + C(K,2) ชิ้น การหาว่าชิ้นไหนหน้าตาอย่างไรทำได้ตรงๆ:
   ไล่ทุกรูปแบบของ "อยู่ฝั่งไหนของแต่ละเส้น" (2^K แบบ) แล้ว clip สี่เหลี่ยมจอ
   ด้วยครึ่งระนาบตามรูปแบบนั้น เหลือรูปอะไรก็คือชิ้นนั้น รูปที่ว่างเปล่าคือ
   รูปแบบที่เป็นไปไม่ได้ทางเรขาคณิต ทิ้งไป

   K = 4 เส้น จึงได้ราว 9-11 ชิ้น กำลังพอดี — มากกว่านี้ชิ้นจะเล็กจนดูเป็นเศษผง

   คำนวณเป็นพิกเซลก่อนแล้วค่อยแปลงเป็น % ตอนท้าย เพราะ clip-path คิดแกน x
   เทียบความกว้างและแกน y เทียบความสูง ถ้าคำนวณมุมใน % ตรงๆ เส้นจะเบี้ยว
   ตามสัดส่วนจอ (บทเรียนเดียวกับที่ทำให้ดาบเคยฟันคนละแนวกับรอยตัด)
   ========================================================================= */

/* ตัดรูปหลายเหลี่ยมด้วยครึ่งระนาบ — Sutherland–Hodgman
   เก็บจุดที่อยู่ฝั่งที่ต้องการไว้ และแทรกจุดตัดตรงที่ขอบข้ามเส้น */
function clipHalf(poly, ln, side) {
  const f = (p) => side * ((p[0] - ln.x) * ln.nx + (p[1] - ln.y) * ln.ny);
  const out = [];
  for (let i = 0; i < poly.length; i++) {
    const a = poly[i], b = poly[(i + 1) % poly.length];
    const fa = f(a), fb = f(b);
    if (fa >= 0) out.push(a);
    if ((fa >= 0) !== (fb >= 0)) {
      const t = fa / (fa - fb);
      out.push([a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t]);
    }
  }
  return out;
}

function shardPolys(W, H, seed = 5) {
  const jit = (n) => {
    const v = Math.sin(n * 78.233 + seed * 41.7) * 43758.5453;
    return v - Math.floor(v);
  };

  /* เส้นฟันสี่เส้น — มุมกระจายกันพอควรและจุดผ่านเยื้องจากกึ่งกลางคนละทาง
     ถ้าทุกเส้นผ่านใกล้จุดเดียวกัน จะกลับไปได้ชิ้นแบบแฉกเหมือนเดิม */
  const lines = [
    { deg:  14, ox: -0.06, oy: -0.10 },
    { deg: -37, ox:  0.10, oy:  0.04 },
    { deg:  62, ox: -0.14, oy:  0.12 },
    { deg: -72, ox:  0.05, oy: -0.16 },
  ].map((l, i) => {
    const a = ((l.deg + (jit(i) - 0.5) * 12) * Math.PI) / 180;
    return {
      x: W * (0.44 + l.ox + (jit(i + 10) - 0.5) * 0.06),
      y: H * (0.48 + l.oy + (jit(i + 20) - 0.5) * 0.06),
      nx: Math.cos(a), ny: Math.sin(a),      // เวกเตอร์ตั้งฉากกับเส้น
    };
  });

  const rect = [[0, 0], [W, 0], [W, H], [0, H]];
  const area = (p) => Math.abs(p.reduce((s, a, i) => {
    const b = p[(i + 1) % p.length];
    return s + (a[0] * b[1] - b[0] * a[1]);
  }, 0) / 2);

  const out = [];
  for (let mask = 0; mask < (1 << lines.length); mask++) {
    let poly = rect;
    for (let i = 0; i < lines.length && poly.length >= 3; i++) {
      poly = clipHalf(poly, lines[i], (mask >> i) & 1 ? 1 : -1);
    }
    // ทิ้งชิ้นที่เล็กกว่า 1.2% ของจอ — เศษเล็กเกินไปมองไม่เห็นแต่กิน DOM
    if (poly.length >= 3 && area(poly) > W * H * 0.012) out.push(poly);
  }

  const f = (n) => n.toFixed(2);

  /* คืนเส้นที่ใช้ตัดออกไปด้วย เพื่อให้เส้นที่วาบให้คนเห็นเป็น "เส้นเดียวกับที่จอแตกจริง"

     ก่อนหน้านี้สองอย่างนี้ใช้มุมคนละชุด ตาจึงเห็นฟันตรงหนึ่งแต่จอแตกอีกตรงหนึ่ง
     ซึ่งเป็นสาเหตุหลักที่ทำให้ท่านี้ดูแปลกทั้งที่แต่ละส่วนถูกต้องในตัวเอง

     มุมหมุนของแท่งใน CSS เท่ากับมุมของเวกเตอร์ตั้งฉากพอดี เพราะแท่งตั้งฉากอยู่แล้ว
     หมุนไปเท่าไหร่ เส้นก็เอียงไปเท่านั้น */
  const cutLines = lines.map((l) => ({
    deg:  +((Math.atan2(l.ny, l.nx) * 180) / Math.PI).toFixed(2),
    left: +((l.x / W) * 100).toFixed(2),
    top:  +((l.y / H) * 100).toFixed(2),
  }));

  const shards = out.map((poly, i) => {
    const cx = poly.reduce((s, p) => s + p[0], 0) / poly.length;
    const cy = poly.reduce((s, p) => s + p[1], 0) / poly.length;

    /* ทิศเลื่อน: ออกจากกึ่งกลางจอตามตำแหน่งของชิ้นเอง + ถ่วงลงเสมอ

       ระยะสั้นและหมุนน้อยโดยตั้งใจ — ของที่ถูกดาบคมเฉือนจะ "เลื่อนแยกแล้วร่วง"
       ไม่ใช่ "ระเบิดกระจาย" ของเดิมเลื่อนไกลถึง 82% และหมุนถึง 18 องศา
       ซึ่งอ่านเป็นเศษซากปลิว ไม่ใช่รอยฟันที่คม */
    const vx = (cx - W / 2) / (W / 2);
    const vy = (cy - H / 2) / (H / 2);
    const len = Math.hypot(vx, vy) || 1;

    return {
      clip:  `polygon(${poly.map(([x, y]) => `${f((x / W) * 100)}% ${f((y / H) * 100)}%`).join(", ")})`,
      dx:    +((vx / len) * (22 + jit(i + 40) * 22)).toFixed(1),
      dy:    +((vy / len) * (16 + jit(i + 50) * 16) + 20 + jit(i + 60) * 16).toFixed(1),
      rot:   +((jit(i + 70) - 0.5) * 7).toFixed(1),
      delay: Math.round(jit(i + 80) * 190),
    };
  });

  return { shards, cutLines };
}

