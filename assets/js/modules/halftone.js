;(function (PF) {
"use strict";

/* ============================================================================
   halftone.js — เปลี่ยนรูปถ่ายให้เป็นเม็ดจุดคอมิก แล้วคลี่ออกเป็นรูปจริง

   งานของไฟล์นี้เล็กกว่าที่คิดมาก: ตัวเอฟเฟกต์ทั้งหมดเป็น CSS
   (ดู [data-halftone] ใน assets/css/components.css และ --ht-screen ใน tokens.css)
   ไฟล์นี้ทำหน้าที่เดียวคือบอก CSS ว่า "รูปในกรอบนี้อยู่ที่ไหน"

   ---------------------------------------------------------------------------
   ทำไมต้องมี JS มาบอก ทำไม CSS อ่านเองไม่ได้

   ชั้นเม็ดจุดเป็น ::after ที่ต้องใช้รูปเดียวกับ <img> ข้างในเป็น background
   แต่ CSS อ่านค่า src ของ element อื่นไม่ได้ จึงต้องมีใครสักคนคัดลอกที่อยู่รูป
   มาใส่ตัวแปร --shot ให้

   ---------------------------------------------------------------------------
   ทำไมไม่ทำด้วย canvas ซึ่งได้ผลแม่นกว่า

   วิธีมาตรฐานของ halftone คืออ่านค่าความสว่างรายพิกเซลด้วย getImageData()
   แล้ววาดวงกลมขนาดตามค่านั้น — ซึ่งใช้กับเว็บนี้ไม่ได้เลย

   เว็บนี้ต้องดับเบิลคลิกไฟล์แล้วใช้ได้ทันที (โปรโตคอล file://) ซึ่งเบราว์เซอร์
   ถือว่าไฟล์แต่ละไฟล์มี origin เป็น null คนละอันกัน พอ drawImage รูปในเครื่อง
   ลง canvas ตัว canvas จะถูกทำเครื่องหมายว่า "ปนเปื้อน" (tainted) แล้ว
   getImageData จะโยน SecurityError ทิ้งทันที

   ผลคือเอฟเฟกต์จะพังเฉพาะตอนเปิดจากไฟล์ ซึ่งเป็นวิธีเปิดหลักของเว็บนี้พอดี
   และจะดูปกติดีตอนทดสอบผ่านเซิร์ฟเวอร์ — บั๊กแบบที่หายากที่สุด

   วิธี CSS ล้วนที่ใช้แทนไม่แตะพิกเซลเลย จึงไม่มีเรื่อง origin มาเกี่ยวข้อง
   ========================================================================= */

/* ที่อยู่รูปถูกเอาไปวางใน url("...") ของ CSS ต้องหนีอักขระที่จะทำให้สตริงขาด
   ชื่อไฟล์ในเว็บนี้ปลอดภัยอยู่แล้ว แต่ media.js สลับเป็น data URI ได้ตอนรัน
   และในอนาคตอาจมีชื่อไฟล์ที่มีวงเล็บหรือช่องว่าง */
const cssUrl = (src) =>
  `url("${String(src).replace(/\\/g, "\\\\").replace(/"/g, '\\"')}")`;

/**
 * ผูกกรอบรูปหนึ่งกรอบ
 * ตั้ง data-halftone="on" ก็ต่อเมื่อมีรูปจริงให้ใช้เท่านั้น
 * CSS เลือกด้วยค่า "on" ไม่ใช่แค่การมีแอตทริบิวต์ ชั้นจุดจึงไม่มีวันโผล่มา
 * ทับรูปที่ยังโหลดไม่เสร็จหรือโหลดไม่สำเร็จ
 */
function bind(box) {
  if (!box || box.dataset.halftone === "on") return;

  const img = box.querySelector("img");
  if (!img) return;

  const apply = () => {
    /* ภาพแทนที่จาก media.js เป็นลายทแยงกับตัวหนังสือ ไม่ใช่รูปถ่าย
       เอามาทำเม็ดจุดแล้วได้แค่ลายมั่วที่อ่านไม่ออกว่าเป็นอะไร — ข้ามไป
       ผลคือช่องที่ยังไม่มีรูปจริงจะแสดงภาพแทนที่ตามปกติเหมือนเดิมทุกอย่าง */
    if (img.dataset.placeheld === "true") return;
    if (!img.naturalWidth) return;

    box.style.setProperty("--shot", cssUrl(img.currentSrc || img.src));
    box.dataset.halftone = "on";
  };

  // โหลดเสร็จไปแล้วก่อนที่เราจะมาถึง (รูปจากแคช) — ใช้ได้เลย
  if (img.complete) { apply(); return; }

  /* ยังโหลดไม่เสร็จ: รอ load
     ไม่ต้องดัก error เอง เพราะ media.js ดักไว้แล้วและจะสลับ src เป็นภาพแทนที่
     ซึ่งจะยิง load อีกรอบ — ตอนนั้น data-placeheld ถูกตั้งแล้ว apply() จะข้ามเอง
     (media.js ถูกเรียกจาก main.js ก่อนไฟล์นี้เสมอ ดูลำดับใน boot()) */
  img.addEventListener("load", apply, { once: true });
}

function initHalftone(scope = document) {
  /* ผู้ใช้ที่ปิดแอนิเมชันไม่ได้อะไรจากไฟล์นี้เลย และไม่ควรได้
     ชั้นจุดคือ "สถานะก่อนเฉลย" ที่มีความหมายก็ต่อเมื่อมันคลี่ออกได้
     ถ้าคลี่ไม่ได้ มันจะกลายเป็นแผ่นบังรูปถาวร — แย่กว่าไม่มีเอฟเฟกต์มาก */
  if (matchMedia("(prefers-reduced-motion: reduce)").matches) return;

  scope.querySelectorAll("[data-halftone]").forEach(bind);

  /* ⚠ ธงต้องเป็น data-halftone-fx ห้ามใช้ data-halftone
     ชื่อหลังตรงกับตัวเลือกที่ CSS ใช้หากรอบรูป (data-halftone="on") พอดี
     ถ้าตั้งชื่อนั้นที่ <html> ตัว <html> จะกลายเป็นกรอบรูปไปด้วย แล้วได้
     position: relative กับชั้น ::after ทับเต็มหน้าโดยไม่มีใครสั่ง
     (เจอตอนทดสอบจริง — ตั้งชื่อพ้องกันแล้วมันเข้าเงื่อนไขเงียบๆ)

     ชื่อลงท้าย -fx ตรงกับที่โมดูลอื่นทำอยู่แล้ว เช่น data-comic-fx ของ comic-fx.js */
  document.documentElement.dataset.halftoneFx = "on";
}

Object.assign(PF, { initHalftone });
})(window.PF = window.PF || {});
